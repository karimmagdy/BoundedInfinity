import glob
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

from scipy import stats

R = Path(__file__).resolve().parent / "results"
SEM = "semantic_reconstruction_quality"


def load(pattern):
    return [json.loads(l) for f in sorted(glob.glob(str(R / "round2" / pattern)))
            for l in open(f) if l.strip()]


def ms(xs):
    return st.mean(xs), (st.stdev(xs) / len(xs) ** 0.5 if len(xs) > 1 else 0.0)


def cells(recs, key):
    c = defaultdict(dict)
    for r in recs:
        c[key(r)][r["seed"]] = r
    return c


def row(rs, metric=SEM):
    m, s = ms([r["quality"][metric] for r in rs])
    return f"{m:.3f} ± {s:.3f}"


def paired(a, b, metric=SEM):
    seeds = sorted(set(a) & set(b))
    xa = [a[s]["quality"][metric] for s in seeds]
    xb = [b[s]["quality"][metric] for s in seeds]
    d = [x - y for x, y in zip(xa, xb)]
    p = stats.ttest_rel(xa, xb).pvalue if any(d) else float("nan")
    return f"diff {st.mean(d):+.3f} ± {ms(d)[1]:.3f}, wins {sum(x > 0 for x in d)}/{len(d)}, paired t p={p:.3f}"


def table(title, c, keys, metric_cols=(("sem", SEM), ("qs", "query_success_rate"),
                                         ("nonempty", "nonempty_success_rate"), ("jacc", "reconstruction_quality"))):
    print(f"\n## {title}\n")
    print("| cell | n | " + " | ".join(n for n, _ in metric_cols) + " |")
    print("|---|---|" + "---|" * len(metric_cols))
    for k in keys:
        rs = list(c.get(k, {}).values())
        if rs:
            print(f"| {k} | {len(rs)} | " + " | ".join(row(rs, m) for _, m in metric_cols) + " |")


sweep = load("sweep.*.jsonl") + load("baselines.*.jsonl")
cs = cells(sweep, lambda r: (r["backend"], r["cache_size"]))
arms = ["bic", "bic-aw", "lru-summary-aw-pin", "lru", "lru-summary", "lru-summary-aw", "lru-pin"]
print("# Round-2 numbers (generated by experiments/extract_round2_numbers.py; do not edit by hand)")
print("\nModel: GPT-5.4 (Azure, gpt-5.4-2026-03-05), reasoning_effort=none, 50-agent research "
      "decomposition (k=3, d=3, 40 agents), seeds 42/123/7/2024/314, mean ± s.e.m.")
table("Sweep (BFS)", cs, [(a, c) for c in (8, 16, 32) for a in arms] + [("unbounded", None)])

print("\n## Paired comparisons (sweep)\n")
for c in (8, 16, 32):
    print(f"- cache {c}: bic-aw vs combined: {paired(cs[('bic-aw', c)], cs[('lru-summary-aw-pin', c)])}")
    print(f"- cache {c}: bic-aw vs bic: {paired(cs[('bic-aw', c)], cs[('bic', c)])}")
    print(f"- cache {c}: bic vs combined: {paired(cs[('bic', c)], cs[('lru-summary-aw-pin', c)])}")

print("\n## BIC-aw diagnostics (sweep)\n")
for c in (8, 16, 32):
    rs = list(cs[("bic-aw", c)].values())
    hit = st.mean(r["quality"]["cache_hit_rate"] for r in rs)
    ipr = [r["quality"]["info_preservation_ratio"] for r in rs]
    ev = st.mean(r["evictions"] for r in rs)
    calls = st.mean(r["llm_usage"]["total_calls"] for r in rs)
    wall = st.mean(r["wall_time_s"] for r in rs)
    print(f"- cache {c}: hit rate {hit:.3f} (queries needing a registry walk {1 - hit:.3f}); "
          f"IPR mean {st.mean(ipr):.3f} min {min(ipr):.3f}; evictions/run {ev:.0f}; "
          f"LLM calls/run {calls:.0f}; wall time/run {wall:.0f} s")
allipr = [r["quality"]["info_preservation_ratio"] for k, v in cs.items() if k[0] == "bic-aw" for r in v.values()]
print(f"- IPR over all 15 bic-aw runs: mean {st.mean(allipr):.3f}, median {st.median(allipr):.3f}, "
      f"min {min(allipr):.3f}, max {max(allipr):.3f}")

hashr = load("hash.*.jsonl")
ch = cells(hashr, lambda r: (r["backend"], r["cache_size"]))
table("Cantor vs hash addressing", {**ch, **{k: v for k, v in cs.items() if k[0] == "bic-aw"}},
      [(a, c) for c in (8, 16, 32) for a in ("bic-aw", "bic-hash")])
for c in (8, 16, 32):
    print(f"- cache {c}: bic-hash vs bic-aw: {paired(ch[('bic-hash', c)], cs[('bic-aw', c)])}")

