for a in ("bic-aw", "lru-summary-aw-pin"):
    means = [ms([r["quality"][SEM] for r in co[(a, o)].values()])[0] for o in ("bfs", "dfs", "random")]
    print(f"- {a}: spread across orders {max(means) - min(means):.3f}")
for o in ("bfs", "dfs", "random"):
    print(f"- {o}: bic-aw vs combined: {paired(co[('bic-aw', o)], co[('lru-summary-aw-pin', o)])}")

pilot = load("pilot.*.jsonl")
cp = cells(pilot, lambda r: (r["backend"], r["cache_size"]))
table("Coding pilot (13 agents, 3 seeds)", cp,
      [(a, c) for c in (2, 4, 8) for a in ("bic-aw", "lru-summary-aw-pin", "lru")] + [("unbounded", None)])
for c in (2, 4, 8):
    print(f"- cache {c}: bic-aw vs combined: {paired(cp[('bic-aw', c)], cp[('lru-summary-aw-pin', c)])}")

